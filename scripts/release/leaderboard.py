def check_audio_sources(root: Path) -> list[str]:
    """Every page clip names a dev-split Gemini-TTS WAV that ships in data/audio."""
    errs = []
    src = json.loads((root / AUDIO_SOURCES).read_text())
    manifest = [
        json.loads(x) for x in (root / "data/manifest.jsonl").read_text().splitlines() if x.strip()
    ]
    rows = {(m["sha256"], m["engine"], m["item_id"], m["variant_id"]) for m in manifest}
    for mp3, s in src.items():
        if not (root / "docs/audio" / mp3).exists():
            errs.append(f"audio: {mp3} listed in SOURCES.json but missing")
        h = s["source_sha256"]
        if (h, "gemini", s["item"], s["variant"]) not in rows:
            errs.append(f"audio: {mp3} source is not a Gemini-TTS dev-split row")
        if not (root / "data/audio" / f"{h}.wav").exists():
            errs.append(f"audio: {mp3} source WAV not in data/audio")
    return errs


