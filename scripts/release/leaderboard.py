def _half_up(x: float) -> Decimal:
    return Decimal(repr(x)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


# Two rounding conventions, both as in the paper's Table A2: values from
# paper_leaderboard.json are printed with Python's float formatting (as
# ``voxparity analyze paper`` prints them), while the probe and both-right
# columns were rounded half-up from their 4-decimal stored values (0.745 -> 0.75).
def f2(x: float, half_up: bool = False) -> str:
    return f"{_half_up(x):.2f}" if half_up else f"{x:.2f}"


def s2(x: float, half_up: bool = False) -> str:
    return f"{_half_up(x):+.2f}" if half_up else f"{x:+.2f}"


def ci(d: dict[str, Any], signed: bool = False, half_up: bool = False) -> str:
    f = s2 if signed else f2
    return f"{f(d['mean'], half_up)} [{f(d['lo'], half_up)}, {f(d['hi'], half_up)}]"


