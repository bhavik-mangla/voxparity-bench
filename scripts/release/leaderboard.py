def cell_probe(r: dict[str, Any]) -> str:
    return ci(r["probe"], half_up=True) if r["probe"] else "n/a"


def cell_both(r: dict[str, Any]) -> str:
    return f2(r["both_right"], True) if r["both_right"] is not None else "n/a"


