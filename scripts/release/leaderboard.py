def splice(readme: str, section: str) -> str:
    if START in readme and END in readme:
        a = readme.index(START)
        b = readme.index(END) + len(END) + 1
        return readme[:a] + section + readme[b:]
    anchor = "## Contents"
    if anchor not in readme:
        sys.exit("README has neither leaderboard markers nor the anchor heading")
    return readme.replace(anchor, section + "\n" + anchor, 1)


